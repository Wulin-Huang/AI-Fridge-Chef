def default_shelf_days(name: str) -> int | None:
    """返回常见食材的默认冷藏保质期天数，未知返回 None（不填）。"""
    n = name.strip()
    if n in EXACT_DAYS:
        return EXACT_DAYS[n]
    for keyword, days in sorted(KEYWORD_DAYS, key=lambda kv: len(kv[0]), reverse=True):
        if keyword in n:
            return days
    return None
